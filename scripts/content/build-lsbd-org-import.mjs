// scripts/content/build-lsbd-org-import.mjs
//
// Builds the one-off import of the real lsbd.org documents from the checked-in lists
// in content/lsbd-org/ (scraped 2026-10-02). Connects to nothing. Writes:
//   drizzle/0010_real_site_documents.sql   the CMS rows (apply with scripts/apply-sql.ts)
//   src/lib/lsbd-org-documents.ts          rulemaking history and fixed page links
//
// Run: node scripts/content/build-lsbd-org-import.mjs

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, "content/lsbd-org", f), "utf8"));
const manifest = read("manifest.json");
const { meetings } = read("meetings.json");
const docs = read("documents.json");

function file(url) {
  const f = manifest[url];
  if (!f) throw new Error(`not in manifest: ${url}`);
  if (!fs.existsSync(path.join(root, "public", f.path))) throw new Error(`file missing: ${f.path}`);
  return f;
}

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
// Pathname column: the path without the leading slash, like a blob pathname.
const fileCols = (url) => {
  const f = file(url);
  return `${q(f.path)}, ${q(f.path.slice(1))}, ${f.bytes}`;
};

const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
const DOC_ORDER = { notice: 0, agenda: 1, minutes: 2 };

const sql = [];
sql.push(`-- 0010_real_site_documents.sql
--
-- GENERATED by scripts/content/build-lsbd-org-import.mjs from content/lsbd-org/*.json.
-- Hand-applied, like 0005 (not in the Drizzle journal):
--   npx tsx scripts/apply-sql.ts drizzle/0010_real_site_documents.sql
--
-- Why: the bulletins, meetings and forms in the CMS were invented seed rows whose file
-- links were "#". This replaces them with what www.lsbd.org publishes (scraped
-- 2026-10-02). The PDFs are served by the site itself from public/documents/, so the
-- file columns hold site-relative paths.
--
-- APPLY AFTER (1) 0009_meetings_month_only.sql and (2) the deployment that contains
-- public/documents/ is live; before that the new links would 404.
--
-- RUNS ONCE: it deletes every row in publications, meetings (and their documents) and
-- downloadable_forms, so it refuses to run when real rows are already present.
-- No BEGIN/COMMIT: the runner wraps the file in a transaction.

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.publications WHERE blob_url LIKE '/documents/%')
     OR EXISTS (SELECT 1 FROM public.meeting_documents WHERE blob_url LIKE '/documents/%')
     OR EXISTS (SELECT 1 FROM public.downloadable_forms WHERE blob_url LIKE '/documents/%') THEN
    RAISE EXCEPTION 'the lsbd.org documents are already imported; this file runs once';
  END IF;
END $$;

DELETE FROM public.meeting_documents;
DELETE FROM public.meetings;
DELETE FROM public.publications;
DELETE FROM public.downloadable_forms;
`);

// Publications
sql.push("-- The Bulletin, one per year.");
for (const b of [...docs.bulletins].sort((a, b) => b.year - a.year)) {
  sql.push(
    `INSERT INTO public.publications (title, year, description, blob_url, blob_pathname, file_size_bytes, is_published) VALUES (${q(b.title)}, ${b.year}, ${q(b.description)}, ${fileCols(b.url)}, true);`,
  );
}

// Forms
sql.push("\n-- Forms, applications and lists.");
for (const f of docs.forms) {
  sql.push(
    `INSERT INTO public.downloadable_forms (name, description, category, blob_url, blob_pathname, file_size_bytes, is_external, external_url, sort_order, is_active) VALUES (${q(f.name)}, ${q(f.description)}, ${q(f.category)}, ${fileCols(f.url)}, false, NULL, ${f.sortOrder}, true);`,
  );
}
// forms.htm links the DEA's own forms page from its controlled-substances section.
sql.push(
  `INSERT INTO public.downloadable_forms (name, description, category, blob_url, blob_pathname, file_size_bytes, is_external, external_url, sort_order, is_active) VALUES ('DEA Forms', 'DEA 224 New Application or DEA 106 Theft or Loss Report', 'controlled_substances', NULL, NULL, NULL, true, 'https://www.deadiversion.usdoj.gov/online_forms.htm', 900, true);`,
);

// Meetings. No time is published, so each is stored at 18:00 UTC (midday Central),
// which shows the same calendar day in every US time zone.
sql.push("\n-- Meetings and their documents.");
for (const m of meetings) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(m.date)) throw new Error(`bad date ${m.date}`);
  const monthOnly = m.datePrecision === "month";
  const [y, mo] = m.date.split("-").map(Number);
  const title = monthOnly ? `${m.title} - ${MONTHS[mo - 1]} ${y}` : m.title;
  const docsSorted = [...m.documents].sort((a, b) => DOC_ORDER[a.docType] - DOC_ORDER[b.docType]);
  const values = docsSorted
    .map((d) => `((SELECT id FROM m), ${q(d.docType)}, ${q(d.title)}, ${fileCols(d.url)})`)
    .join(",\n  ");
  sql.push(
    `WITH m AS (INSERT INTO public.meetings (title, meeting_date, description, meeting_type, is_published, date_is_month_only) VALUES (${q(title)}, '${m.date}T18:00:00Z', ${q(m.description)}, ${q(m.type)}, true, ${monthOnly}) RETURNING id)\n` +
      `INSERT INTO public.meeting_documents (meeting_id, doc_type, title, blob_url, blob_pathname, file_size_bytes) VALUES\n  ${values};`,
  );
}

sql.push(`
INSERT INTO public.audit_log (user_id, action, entity_type, entity_id, details)
VALUES (NULL, 'import', 'site_documents', NULL,
  '{"source": "www.lsbd.org", "scraped": "2026-10-02", "publications": ${docs.bulletins.length}, "forms": ${docs.forms.length + 1}, "meetings": ${meetings.length}, "meetingDocuments": ${meetings.reduce((n, m) => n + m.documents.length, 0)}}'::jsonb);
`);

fs.writeFileSync(path.join(root, "drizzle/0010_real_site_documents.sql"), sql.join("\n"));

// Static data for pages that are not CMS-driven.
const link = (url) => ({ href: file(url).path, bytes: file(url).bytes });
const rulemaking = [...docs.rulemaking]
  .sort((a, b) => b.date.localeCompare(a.date))
  .map((r) => ({
    date: r.date,
    title: r.title,
    description: r.description,
    documents: r.documents.map((d) => ({ label: d.label, ...link(d.url) })),
  }));
const reports = [...docs.rulemakingReports]
  .sort((a, b) => b.year - a.year)
  .map((r) => ({ year: r.year, title: r.title, ...link(r.url) }));
const pageLinks = Object.fromEntries(docs.pageLinks.map((p) => [p.purpose, { label: p.label, ...link(p.url) }]));

const ts = `// GENERATED by scripts/content/build-lsbd-org-import.mjs from content/lsbd-org/*.json.
// Documents carried over from www.lsbd.org (scraped 2026-10-02) that pages link
// directly. The files are in public/documents/.

export interface DocumentLink {
  label: string;
  href: string;
  bytes: number;
}

export interface RulemakingProceeding {
  /** Date the summary report was sent, as stated on lsbd.org (YYYY-MM-DD). */
  date: string;
  title: string;
  description: string;
  documents: DocumentLink[];
}

export const RULEMAKING_HISTORY: RulemakingProceeding[] = ${JSON.stringify(rulemaking, null, 2)};

export const RULEMAKING_YEARLY_REPORTS: { year: number; title: string; href: string; bytes: number }[] = ${JSON.stringify(reports, null, 2)};

export const SITE_DOCUMENTS = ${JSON.stringify(pageLinks, null, 2)} as const satisfies Record<string, DocumentLink>;
`;
fs.writeFileSync(path.join(root, "src/lib/lsbd-org-documents.ts"), ts);

const used = new Set([
  ...docs.bulletins.map((x) => x.url),
  ...docs.forms.map((x) => x.url),
  ...meetings.flatMap((m) => m.documents.map((d) => d.url)),
  ...docs.rulemaking.flatMap((r) => r.documents.map((d) => d.url)),
  ...docs.rulemakingReports.map((x) => x.url),
  ...docs.pageLinks.map((x) => x.url),
]);
const unused = Object.keys(manifest).filter((u) => !used.has(u));
console.log(
  `publications ${docs.bulletins.length}, forms ${docs.forms.length + 1}, meetings ${meetings.length}, ` +
    `meeting documents ${meetings.reduce((n, m) => n + m.documents.length, 0)}, rulemaking ${rulemaking.length}, ` +
    `reports ${reports.length}, page links ${docs.pageLinks.length}`,
);
console.log(`files in manifest ${Object.keys(manifest).length}, linked ${used.size}, not linked anywhere ${unused.length}:`);
for (const u of unused) console.log("  " + u);
